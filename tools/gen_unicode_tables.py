"""Write web/engine/unitables.js: the Unicode tables the JavaScript port needs to take the helper's decisions, computed
with the helper's Python (3.11, Unicode 14) over every code point:
  DIGIT_EXTRA      str.isdigit() characters outside \\p{Nd} (superscripts, circled digits...), as ranges
  CASEFOLD         str.casefold() where it differs from str.lower(), per character
  NAME_OK          alphabetic characters whose Unicode name starts with LATIN / GREEK / MICRO SIGN (the sanity
                   gate's script test, translate._suspect), as ranges
  LOWER_IRREGULAR  characters whose simple lower case (_sre.unicode_tolower, used by re.I) does not give them back
                   through upper() as one code point
  CASE_EXTRA       re._casefix._EXTRA_CASES: the characters re.I matches besides the simple case mappings, keyed by
                   the lower-case character (re._compiler's `fixes`)
Usage: gen_unicode_tables.py   (Python = the vitranslate env). Output is ASCII.
"""
import _sre
import sys
import unicodedata
from pathlib import Path
from re._casefix import _EXTRA_CASES

OUT = Path(__file__).resolve().parents[1] / "web" / "engine" / "unitables.js"
OK = ("LATIN", "GREEK", "MICRO SIGN")


def code_points():
    return (cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF)


def ranges(cps):
    out, start, prev = [], None, None
    for cp in sorted(cps):
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            out.append((start, prev))
            start = prev = cp
    if start is not None:
        out.append((start, prev))
    return out


def wrap(items, indent="  ", width=118):
    lines, line = [], indent
    for item in items:
        piece = item + ", "
        if len(line) + len(piece.rstrip()) > width:
            lines.append(line.rstrip())
            line = indent
        line += piece
    if line.strip():
        lines.append(line.rstrip().rstrip(","))
    return "\n".join(lines)


def main():
    digit_extra, casefold, name_ok, irregular = [], [], [], []
    for cp in code_points():
        c = chr(cp)
        if c.isdigit() and not c.isdecimal():
            digit_extra.append(cp)
        if c.casefold() != c.lower():
            casefold.append((cp, [ord(x) for x in c.casefold()]))
        if c.isalpha() and unicodedata.name(c, "").startswith(OK):
            name_ok.append(cp)
        lo = _sre.unicode_tolower(cp)
        if lo != cp:
            up = chr(lo).upper()
            if len(up) != 1 or ord(up) != cp:
                irregular.append((cp, lo))
    rng = lambda cps: wrap(["[0x%x, 0x%x]" % r for r in ranges(cps)])  # noqa: E731
    text = "\n".join([
        "// Generated by tools/gen_unicode_tables.py (Python %s, Unicode %s): do not edit." % (
            sys.version.split()[0], unicodedata.unidata_version),
        "// Tables the port needs to take the helper's decisions; see the tool's docstring.",
        "",
        "/** str.isdigit() characters outside \\p{Nd}, as [first, last] ranges. */",
        "export const DIGIT_EXTRA = [\n%s,\n];" % rng(digit_extra),
        "",
        "/** str.casefold() where it differs from str.lower(): [code point, [folded code points]]. */",
        "export const CASEFOLD = [\n%s,\n];" % wrap(["[0x%x, [%s]]" % (cp, ", ".join("0x%x" % x for x in v))
                                                   for cp, v in casefold]),
        "",
        "/** Alphabetic characters whose Unicode name starts with LATIN / GREEK / MICRO SIGN, as ranges. */",
        "export const NAME_OK = [\n%s,\n];" % rng(name_ok),
        "",
        "/** [character, its simple lower case] where upper() of that lower case is not the character. */",
        "export const LOWER_IRREGULAR = [\n%s,\n];" % wrap(["[0x%x, 0x%x]" % p for p in irregular]),
        "",
        "/** re._casefix._EXTRA_CASES: [lower-case character, [the other characters re.I matches with it]]. */",
        "export const CASE_EXTRA = [\n%s,\n];" % wrap(["[0x%x, [%s]]" % (k, ", ".join("0x%x" % x for x in v))
                                                     for k, v in sorted(_EXTRA_CASES.items())]),
        "",
    ])
    OUT.write_text(text, encoding="ascii", newline="\n")
    print("wrote %s: %d digit extras, %d casefold, %d name-ok (%d ranges), %d irregular, %d case extras" % (
        OUT.name, len(digit_extra), len(casefold), len(name_ok), len(ranges(name_ok)), len(irregular),
        len(_EXTRA_CASES)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
